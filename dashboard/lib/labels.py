def model_color_index(model: str, selected: list) -> int:
    """在已选模型集合里，该模型占第几个配色槽位。

    按 MODEL_ORDER 的固定次序排名，因此筛选后幸存序列的颜色不被重排
    （color follows the entity, not its row number）。
    """
    ordered = [m for m in MODEL_ORDER if m in selected]
    return ordered.index(model)
